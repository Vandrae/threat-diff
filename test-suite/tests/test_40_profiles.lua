  t.ok(TD:DeleteProfile("Gone"))
  t.eq(_G.ThreatDiffDB.chars["Alt - Testrealm"], nil)
end)

test("profiles: copy replaces the current profile; reset wipes it", function(t)
  local W, TD = t:boot()
  TD.db.x = 99; TD.db.colors.SECURE = { 0, 0, 0 }
  TD:NewProfile("Other"); TD.db.x = 5
  t.ok(TD:CopyProfile("Default"))
  t.eq(TD.db.x, 99); t.eq(TD.db.colors.SECURE[1], 0)
  local ok, err = TD:CopyProfile("Other"); t.eq(ok, false); t.has(err, "different profile")
  TD:ResetProfile()
  t.eq(TD.db.x, -6); t.eq(TD.db.colors.SECURE[1], 0.25)
  t.eq(_G.ThreatDiffDB.profiles.Default.x, 99, "other profiles untouched by reset")
end)

test("profiles: ProfileUsers lists characters on a profile", function(t)
  local W, TD = t:boot({ saved = { profiles = { Default = {}, Raid = {} },
    chars = { ["Zed - Testrealm"] = "Raid", ["Amy - Testrealm"] = "Raid" } } })
  local u = TD:ProfileUsers("Raid")
  t.eq(#u, 2); t.eq(u[1], "Amy - Testrealm")
end)

test("profiles: slash commands list/use/new/copy/delete/reset", function(t)
  local W, TD = t:boot()
  TD.db.x = 3
  t.has(slash(t, "profile"), "Default")
  t.has(slash(t, "profile new Raid"), "created and switched to")
  t.eq(TD.profileName, "Raid")
  t.has(slash(t, "profile new Raid"), "already exists")
  TD.db.x = 8
  t.has(slash(t, "profile use default"), "now using profile")
  t.eq(TD.profileName, "Default"); t.eq(TD.db.x, 3)
  t.has(slash(t, "profile use nope"), "no profile")
  t.has(slash(t, "profile copy raid"), "copied")
  t.eq(TD.db.x, 8)
  t.has(slash(t, "profile delete raid"), "deleted")
  t.has(slash(t, "profile delete Default"), "can't be deleted")
  t.has(slash(t, "profile reset"), "reset to defaults")
  t.eq(TD.db.x, -6)
  t.has(slash(t, "profile bogus"), "usage")
  t.has(slash(t, "profiles list"), "profiles")
  t.has(slash(t, "profile switch default"), "now using")
end)

