local test = T.test

local function slash(t, msg)
  t.W.clearChat()
  SlashCmdList.THREATDIFF(msg)
  return t.W.chatText()
end

test("profiles: fresh install creates Default with all defaults", function(t)
  local W, TD = t:boot()
  t.eq(TD.profileName, "Default")
  t.eq(TD.db.x, -6); t.eq(TD.db.meter.width, 260); t.eq(TD.db.colors.SECURE[2], 1)
  t.eq(_G.ThreatDiffDB.chars["Tester - Testrealm"], "Default")
  t.eq(_G.ThreatDiffDB.version, 2)
  t.ok(_G.ThreatDiffDB.minimap and _G.ThreatDiffDB.minimap.hide == false)
end)

test("profiles: an old flat save is moved into Default without losing values", function(t)
  local W, TD = t:boot({ saved = { x = 5, y = 3, enabled = false, role = "TANK",
    meter = { width = 333 }, colors = { SECURE = { 0.1, 0.2, 0.3 } }, saved = true } })
  t.eq(TD.profileName, "Default")
  t.eq(TD.db.x, 5); t.eq(TD.db.y, 3); t.eq(TD.db.enabled, false); t.eq(TD.db.role, "TANK")
  t.eq(TD.db.meter.width, 333); t.eq(TD.db.meter.height, 214, "new keys are filled from defaults")
  t.eq(TD.db.colors.SECURE[1], 0.1)
  t.eq(TD.db.colors.TANKING[1], 1, "missing colours are filled in")
  t.eq(_G.ThreatDiffDB.x, nil, "old flat keys removed from the root")
  t.eq(_G.ThreatDiffDB.profiles.Default.saved, nil)
end)

test("profiles: a save from the row-count meter era keeps its size as a fixed height", function(t)
  local W, TD = t:boot({ saved = { profiles = { Default = { meter = { maxBars = 5, barHeight = 18, spacing = 1 } } }, chars = {} } })
  t.eq(TD.db.meter.height, TD.MeterHeightFor(5, 18, 1))
