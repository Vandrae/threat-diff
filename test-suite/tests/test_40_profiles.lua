test("profiles: delete rules", function(t)
  local W, TD = t:boot()
  TD:NewProfile("A"); TD:NewProfile("B")
  local ok, err = TD:DeleteProfile("B"); t.eq(ok, false); t.has(err, "switch to another")
  ok, err = TD:DeleteProfile("Default"); t.eq(ok, false); t.has(err, "can't be deleted")
  ok, err = TD:DeleteProfile("zzz"); t.eq(ok, false)
  t.ok(TD:DeleteProfile("A"))
  t.eq(_G.ThreatDiffDB.profiles.A, nil)
  t.eq(#TD:GetProfiles(), 2)
end)

