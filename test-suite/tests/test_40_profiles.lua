test("profiles: new / switch / duplicate keep settings independent", function(t)
  local W, TD = t:boot()
  TD.db.x = 7
  t.ok(TD:NewProfile("Tank"))
  t.eq(TD.profileName, "Tank"); t.eq(TD.db.x, -6, "new profile starts from defaults")
  TD.db.x = 1
  t.ok(TD:NewProfile("Tank copy", "Default"))
  t.eq(TD.db.x, 7, "copy of Default")
  t.ok(TD:SetProfile("tank"), "case-insensitive switch")
  t.eq(TD.profileName, "Tank"); t.eq(TD.db.x, 1)
  t.eq(_G.ThreatDiffDB.chars["Tester - Testrealm"], "Tank")
  local list = TD:GetProfiles()
  t.eq(list[1], "Default"); t.eq(#list, 3)
end)

test("profiles: name validation", function(t)
  local W, TD = t:boot()
  local ok, err = TD:NewProfile("   "); t.eq(ok, false); t.has(err, "1%-40")
  ok, err = TD:NewProfile(string.rep("x", 41)); t.eq(ok, false)
  ok, err = TD:NewProfile("Default"); t.eq(ok, false); t.has(err, "already exists")
  ok, err = TD:NewProfile("DEFAULT"); t.eq(ok, false, "names are not case sensitive")
  ok = TD:NewProfile("  Padded  "); t.eq(ok, true); t.eq(TD.profileName, "Padded", "whitespace trimmed")
  ok, err = TD:SetProfile("nope"); t.eq(ok, false); t.has(err, "no profile")
end)

test("profiles: rename moves characters over; Default cannot be renamed", function(t)
  local W, TD = t:boot()
  TD:NewProfile("Raid")
  TD.db.x = 4
  t.ok(TD:RenameProfile("Raid", "Raids"))
  t.eq(TD.profileName, "Raids"); t.eq(TD.db.x, 4)
  t.eq(_G.ThreatDiffDB.chars["Tester - Testrealm"], "Raids")
  t.eq(_G.ThreatDiffDB.profiles.Raid, nil)
  local ok, err = TD:RenameProfile("Default", "X"); t.eq(ok, false); t.has(err, "can't be renamed")
  TD:NewProfile("Other")
  ok, err = TD:RenameProfile("Other", "raids"); t.eq(ok, false); t.has(err, "already exists")
  t.ok(TD:RenameProfile("Raids", "raids"), "changing only the case is allowed")
  t.ok(_G.ThreatDiffDB.profiles.raids, "renamed to lower case")
  t.eq(_G.ThreatDiffDB.profiles.Raids, nil)
end)

test("profiles: renaming to the identical name keeps the profile (the Rename box is pre-filled with the old name)", function(t)
  local W, TD = t:boot()
  TD:NewProfile("Raid"); TD.db.x = 4
  t.ok(TD:RenameProfile("Raid", "Raid"))
  t.ok(_G.ThreatDiffDB.profiles.Raid, "profile must not vanish")
