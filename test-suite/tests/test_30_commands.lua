test("slash: probe arms out of combat, reports in combat", function(t)
  local W, TD = t:boot()
  local mob = t:engage("nameplate1", "Boar", true)
  t:set(mob, W.player, 5000, { tank = true })
  t.has(slash(t, "probe"), "probe armed")
  t.eq(TD.probeArmed, true)
  W.enterCombat(); W.advance(3.1)
  local out = W.chatText()
  t.has(out, "probe %- in combat")
  t.has(out, "target")
  t.has(out, "routes:")
  t.eq(TD.probeArmed, false)
  -- in-combat call reports immediately; secret values are flagged
  W.hideOnPlates = true
  W.clearChat()
  SlashCmdList.THREATDIFF("debug")
  t.has(W.chatText(), "SECRET")
  t.has(W.chatText(), "enemy plates")
end)

