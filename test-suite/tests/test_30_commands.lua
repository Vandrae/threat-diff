local test = T.test

local function slash(t, msg)
  t.W.clearChat()
  SlashCmdList.THREATDIFF(msg)
  return t.W.chatText()
end

test("slash: /tdiff and /threatdiff are both registered", function(t)
  t:boot()
  t.eq(_G.SLASH_THREATDIFF1, "/tdiff")
  t.eq(_G.SLASH_THREATDIFF2, "/threatdiff")
  t.ok(SlashCmdList.THREATDIFF)
end)

test("slash: bare /tdiff, config and options open the settings window", function(t)
  local W, TD = t:boot()
  slash(t, "")
  t.ok(_G.ThreatDiffConfig and _G.ThreatDiffConfig:IsShown(), "window should open")
  slash(t, "")
  t.eq(_G.ThreatDiffConfig:IsShown(), false, "second call closes it")
  slash(t, "config"); t.eq(_G.ThreatDiffConfig:IsShown(), true)
  slash(t, "options"); t.eq(_G.ThreatDiffConfig:IsShown(), false)
end)

test("slash: pos prints, sets both axes, accepts every documented spelling", function(t)
  local W, TD = t:boot()
  t.has(slash(t, "pos"), "x %-6%.00, y 0%.00")
  slash(t, "pos 2.34 10.25");            t.eq(TD.db.x, 2.34); t.eq(TD.db.y, 10.25)
  slash(t, "pos 1.5, -3");               t.eq(TD.db.x, 1.5);  t.eq(TD.db.y, -3)
  slash(t, "pos x, 4.5 y, -7.25");       t.eq(TD.db.x, 4.5);  t.eq(TD.db.y, -7.25)
  slash(t, "pos x 8 y 9");               t.eq(TD.db.x, 8);    t.eq(TD.db.y, 9)
  slash(t, "pos y=2");                   t.eq(TD.db.x, 8);    t.eq(TD.db.y, 2)
  slash(t, "pos x=-0.5");                t.eq(TD.db.x, -0.5); t.eq(TD.db.y, 2)
  slash(t, "pos 7");                     t.eq(TD.db.x, 7);    t.eq(TD.db.y, 2)
  slash(t, "pos 1.005 2.345");           t.eq(TD.db.x, 1.01); t.eq(TD.db.y, 2.35)
  slash(t, "POS 3 4");                   t.eq(TD.db.x, 3);    t.eq(TD.db.y, 4)
  slash(t, "xy 5 6");                    t.eq(TD.db.x, 5);    t.eq(TD.db.y, 6)
  slash(t, "position 9 9");              t.eq(TD.db.x, 9)
end)

