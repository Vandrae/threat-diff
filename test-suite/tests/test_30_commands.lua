test("slash: ParseXY handles each README form", function(t)
  local W, TD = t:boot()
  local function xy(s) local x, y = TD.ParseXY(s); return x, y end
  local x, y = xy("2.34 10.25"); t.eq(x, 2.34); t.eq(y, 10.25)
  x, y = xy("x, 2.34 y, 10.25"); t.eq(x, 2.34); t.eq(y, 10.25)
  x, y = xy("-6 0"); t.eq(x, -6); t.eq(y, 0)
  x, y = xy("+3 -2"); t.eq(x, 3); t.eq(y, -2)
  x, y = xy(".5 .25"); t.eq(x, 0.5); t.eq(y, 0.25)
  x, y = xy("nothing"); t.eq(x, nil); t.eq(y, nil)
end)
